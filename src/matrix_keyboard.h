#ifndef MATRIX_KEYBOARD_H
#define MATRIX_KEYBOARD_H

#include <cstdint>
#include "config.h"

// ═══════════════════════════════════════════════════════════════════════════
//  СДВИГОВЫЕ РЕГИСТРЫ: ИНИЦИАЛИЗАЦИЯ И УПРАВЛЕНИЕ
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Инициализация GPIO для работы со сдвиговыми регистрами
 * (74HC595 для выводов строк, 74HC165 для чтения столбцов)
 */
void initShiftRegisters();

/**
 * Отправить 16-битные данные в 74HC595 (управление строками матрицы)
 * 
 * @param rowData - 16 бит для управления строками (2 чипа по 8 бит)
 */
void shiftOut595(uint16_t rowData);

/**
 * Прочитать 8-битные данные из 74HC165 (состояние столбцов)
 * 
 * @return 8 бит со статусом нажатия столбцов
 */
uint8_t shiftIn165();

// ═══════════════════════════════════════════════════════════════════════════
//  МАТРИЧНАЯ КЛАВИАТУРА: СКАНИРОВАНИЕ
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Отсканировать всю матричную клавиатуру
 * 
 * @return true если состояние изменилось
 */
bool scanMatrixKeyboard();

/**
 * Получить состояние одной клавиши матрицы
 * 
 * @param row - строка (0..MATRIX_ROWS-1)
 * @param col - столбец (0..MATRIX_COLS-1)
 * @return true если клавиша нажата
 */
bool getMatrixKey(int row, int col);

#endif // MATRIX_KEYBOARD_H
