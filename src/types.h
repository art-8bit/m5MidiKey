#ifndef TYPES_H
#define TYPES_H

#include <cstdint>
#include "esp_bt.h"

// ═══════════════════════════════════════════════════════════════════════════
//  РЕЖИМЫ ПРИЛОЖЕНИЯ
// ═══════════════════════════════════════════════════════════════════════════
enum class AppMode : uint8_t {
    MENU = 0,
    PLAY = 1
};

// ═══════════════════════════════════════════════════════════════════════════
//  ПУНКТЫ МЕНЮ
// ═══════════════════════════════════════════════════════════════════════════
enum class MenuItemID : uint8_t {
    OCTAVE         = 0,
    VELOCITY       = 1,
    BLE_POWER      = 2,
    MIDI_CHANNEL   = 3,
    KBD_SOURCE     = 4,
    MATRIX_ENABLED = 5,
    PLAY           = 6,
    COUNT          = 7
};

// Источник клавиатуры
enum class KeyboardSource : uint8_t {
    BUILT_IN = 0,  // только встроенная
    MATRIX   = 1,  // только матричная
    BOTH     = 2   // обе одновременно
};

// ═══════════════════════════════════════════════════════════════════════════
//  BLE POWER TABLE
// ═══════════════════════════════════════════════════════════════════════════
struct BLEPwrEntry {
    const char* label;
    esp_power_level_t level;
};

// ═══════════════════════════════════════════════════════════════════════════
//  МАППИНГ КЛАВИШИ → MIDI
// ═══════════════════════════════════════════════════════════════════════════
struct NoteKey {
    uint8_t key;  // символ клавиши
    int8_t rel;   // смещение относительно C
};

#endif // TYPES_H
