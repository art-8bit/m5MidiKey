#ifndef KEYBOARD_MAP_H
#define KEYBOARD_MAP_H

#include "types.h"
#include "config.h"

// ═══════════════════════════════════════════════════════════════════════════
//  ВСТРОЕННАЯ КЛАВИАТУРА: БЕЛЫЕ НОТЫ
// ═══════════════════════════════════════════════════════════════════════════
// Маппинг: A S D F G H J K L ; → C D E F G A B C5 D5 E5 (белые клавиши)
static constexpr NoteKey WHITE_KEYS[] = {
    {'a',  0}, {'s',  2}, {'d',  4}, {'f',  5}, {'g',  7},
    {'h',  9}, {'j', 11}, {'k', 12}, {'l', 14}, {';', 16},
};
static constexpr int WK_COUNT = sizeof(WHITE_KEYS) / sizeof(WHITE_KEYS[0]);

// ═══════════════════════════════════════════════════════════════════════════
//  ВСТРОЕННАЯ КЛАВИАТУРА: ЧЁРНЫЕ НОТЫ
// ═══════════════════════════════════════════════════════════════════════════
// Маппинг: W E T Y U O P → C# D# F# G# A# C#5 D#5 (чёрные клавиши)
static constexpr NoteKey BLACK_KEYS[] = {
    {'w',  1}, {'e',  3}, {'t',  6}, {'y',  8}, {'u', 10},
    {'o', 13}, {'p', 15},
};
static constexpr int BK_COUNT = sizeof(BLACK_KEYS) / sizeof(BLACK_KEYS[0]);

// ═══════════════════════════════════════════════════════════════════════════
//  ВСТРОЕННАЯ КЛАВИАТУРА: ПОЗИЦИЯ ЧЁРНЫХ КЛАВИШ
// ═══════════════════════════════════════════════════════════════════════════
// Горизонтальная позиция чёрных клавиш относительно белых (для визуализации)
static constexpr float BK_POS[BK_COUNT] = {
    0.6f, 1.6f, 3.6f, 4.6f, 5.6f, 7.6f, 8.6f,
};

#endif // KEYBOARD_MAP_H
