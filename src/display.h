/**
 * Нарисовать строку статуса (вверху экрана)
 * Показывает: название, октаву, батарею, статус BLE
 */
void drawStatusBar();

/**
 * Нарисовать экран меню настроек
 */
void drawMenu();

/**
 * Нарисовать экран режима игры с пианино и информацией о ноте
 */
void drawPlay();

/**
 * Полная перерисовка экрана
 * Вызывает drawStatusBar() и drawMenu() или drawPlay() в зависимости от режима
 */
void redraw();

